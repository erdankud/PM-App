"""Авторская типизация упражнений System Design.

Импортёр не может вывести поля из текста и создаёт все упражнения как `open`.
Здесь для каждого упражнения, эталон которого даёт проверяемый ответ, описаны
поля ввода и приёмка. Всё остальное остаётся `open` намеренно: если ответ
формулируется абзацем, поле с интервалом его не проверит, а сделает вид.

Приёмка числовых полей — интервал порядка величины (спека SD §5.1), а не точное
совпадение: упражнение учит прикидке, и «примерно столько же» здесь и есть
правильный ответ.

Формат:
    "ex-id": {
        "type": "estimation" | "classification",
        "choices": [...],            # значения по умолчанию для pick()
        "inputs": [num(...), pick(...), ...],
    }
"""

from __future__ import annotations


def num(iid: str, label: str, lo: float, hi: float, unit: str | None = None) -> dict:
    field = {"id": iid, "label": label, "type": "number"}
    if unit:
        field["unit"] = unit
    return {"input": field, "rule": {"inputId": iid, "min": lo, "max": hi}}


def pick(iid: str, label: str, expected: str, choices: list[str] | None = None) -> dict:
    field = {"id": iid, "label": label, "type": "choice"}
    if choices is not None:
        field["choices"] = choices
    return {"input": field, "rule": {"inputId": iid, "expected": expected}}


