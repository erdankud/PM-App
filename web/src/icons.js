/** Путь и признак заливки по имени символа — чтобы значок можно было врисовать
 *  в чужой SVG (например, в ячейку карты), а не только вставить отдельным тегом. */
export function iconPath(name) {
  return MAP[name] || [P.dot, true];
}

export function icon(name, { size = 16, className = "" } = {}) {
  const [d, filled] = iconPath(name);
  return svg(
    "svg",
    {
      class: `icon ${className}`.trim(),
      width: size,
      height: size,
      viewBox: "0 0 24 24",
      fill: filled ? "currentColor" : "none",
      stroke: "currentColor",
      "stroke-width": filled ? 1.4 : 1.7,
      "stroke-linecap": "round",
      "stroke-linejoin": "round",
      "aria-hidden": "true",
      focusable: "false",
    },
    svg("path", { d })
  );
}
